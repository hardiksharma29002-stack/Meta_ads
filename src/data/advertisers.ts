// Helper to calculate Jaipur domain spend breakdown
export function getJaipurDomainBreakdown(): DomainSummary[] {
  const jaipurCompanies = ALL_COMPANIES.filter((c) => c.city === "jaipur");
  const groups: Record<string, { totalAds: number; count: number; topCompany: string; maxAds: number }> = {};

  let grandTotalAds = 0;
  for (const c of jaipurCompanies) {
    grandTotalAds += c.active_ads;
    if (!groups[c.domain_group]) {
      groups[c.domain_group] = { totalAds: 0, count: 0, topCompany: c.name, maxAds: 0 };
    }
    groups[c.domain_group].totalAds += c.active_ads;
    groups[c.domain_group].count += 1;
    if (c.active_ads > groups[c.domain_group].maxAds) {
      groups[c.domain_group].maxAds = c.active_ads;
      groups[c.domain_group].topCompany = c.name;
    }
  }

  const summaries: DomainSummary[] = Object.keys(groups).map((domain) => {
    const data = groups[domain];
    const share = Math.round((data.totalAds / grandTotalAds) * 100);
    const avg = Math.round(data.totalAds / data.count);
    const spendIntensity: "Very High" | "High" | "Medium" = 
      avg >= 150 ? "Very High" : avg >= 95 ? "High" : "Medium";

    return {
      name: domain,
      company_count: data.count,
      total_active_ads: data.totalAds,
      share_percent: share,
      avg_ads_per_company: avg,
      spend_intensity: spendIntensity,
      top_advertiser: data.topCompany,
    };
  });

  return summaries.sort((a, b) => b.total_active_ads - a.total_active_ads);
}

